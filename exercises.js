// Library sections → app muscle groups.
const EX_SECTION_GROUP={Chest:'chest',Back:'back',Shoulders:'shoulders',Biceps:'arms',Triceps:'arms',Forearms:'arms',Legs:'legs',Calves:'legs',Core:'core',Cardio:'cardio',Mobility:'mobility'};
// Olympic and functional lifts go where they load the most.
const EX_GROUP_OVERRIDE={'Clean and Press':'legs','Power Clean':'legs','Thruster':'legs','Kettlebell Swing':'legs','Turkish Get-Up':'core','Wall Ball':'legs','Medicine Ball Slam':'core','TRX Row':'back','TRX Push-Up':'chest','Battle Ropes':'cardio','Farmer\'s Walk':'core'};
const EQ_ORDER=['Machine','Cable','Dumbbell','Barbell','Smith Machine','Kettlebell','Bodyweight','Suspension','Other','Yours'];

const _EXIDX={};EXDB.forEach(function(e){_EXIDX[e.n]=e});
function customEx(){return (sGet('profile',{})||{}).customEx||[]}
function exInfo(name){
  if(_EXIDX[name])return _EXIDX[name];
  const c=customEx().filter(function(x){return x.n===name})[0];
  return c?{n:c.n,g:'',eq:'Yours',m:'',t:c.t||'weight',group:c.group}:null;
}
function exGroup(name){
  if(EX_GROUP_OVERRIDE[name])return EX_GROUP_OVERRIDE[name];
  const e=exInfo(name);if(!e)return null;
  return e.group||EX_SECTION_GROUP[e.g]||null;
}
function exercisesInGroup(k){
  const out=EXDB.filter(function(e){return exGroup(e.n)===k});
  customEx().forEach(function(c){if(c.group===k)out.push({n:c.n,g:'',eq:'Yours',m:'',t:c.t||'weight',group:k})});
  return out;
}
// Generic guidance for exercises the plan doesn't prescribe.
function genericDose(name){
  const e=exInfo(name),t=e?e.t:'weight';
  return t==='duration'?'15–30 min':t==='time'?'2 × 30–45 s':t==='reps'?'2–3 × 10–15':'2–3 × 8–12';
}
